SMALL = dict(n=20, m=10, r=3)
BIG = dict(n=40, m=25, r=5)
RHO = {False: 0.12, True: 0.02}


class SeededMethod(Method):
    """Algorithm 1 entered with psi* already raised by cheap efficient points."""

    def __init__(self, inst, seeds=8, cut_seeds=False, seed_rng=0, **kw):
        super().__init__(inst, **kw)
        self.n_seeds = seeds
        self.cut_seeds = cut_seeds
        self.seed_rng = np.random.default_rng(seed_rng)
        self.seed_milps = 0

    def _efficient_by_weights(self, mw, xw):
        """max sum_i lam_i c^i x with lam > 0 -- its optimum is efficient."""
        C = self.I["C"]
        lam = self.seed_rng.random(self.r) + 0.05
        mw.setObjective(
            gp.quicksum(float(sum(lam[i] * C[i, j] for i in range(self.r)))
                        * xw[j] for j in range(self.n)), GRB.MAXIMIZE)
        mw.reset()
        return self._run(mw)

    def _seed(self):
        """Return the best (psi, x) found over S scalarisations, cutting if asked."""
        p, al, q, be = (self.I["p"], self.I["alpha"], self.I["q"], self.I["beta"])
        psi_star, x_star = -np.inf, None
        if self.n_seeds <= 0:
            return psi_star, x_star
        mw, xw = self._new_model()                 # no cuts: these stay cheap
        before = self.milps
        try:
            for _ in range(self.n_seeds):
                xs = self._efficient_by_weights(mw, xw)
                if xs is None or self.truncated:
                    break
                xb, ps = self.find_best(xs)        # best psi on that slice
                if self.truncated:
                    break
                if ps > psi_star:
                    psi_star, x_star = ps, xb
                if self.cut_seeds:
                    self.add_cut(xs)               # valid: slice already maximised
        finally:
            mw.dispose()
            self.seed_milps = self.milps - before
        return psi_star, x_star

    def solve(self, max_rounds=60):
        p, al, q, be = (self.I["p"], self.I["alpha"], self.I["q"], self.I["beta"])
        t_wall = time.perf_counter()
        psi_star, x_star = self._seed()
        bound = None
        if np.isfinite(psi_star):                  # Remark 3.4, from round zero
            bound = self.mR.addConstr(
                gp.quicksum((float(p[j]) - psi_star * float(q[j])) * self.xR[j]
                            for j in range(self.n)) >= psi_star * be - al)
            self.mR.update()

        rounds = 0
        if not self.truncated:
            for _ in range(max_rounds):
                rounds += 1
                x0, psi0 = self.dinkelbach()
                if self.truncated or x0 is None or psi0 <= psi_star + EPS:
                    break
                eff, xp = self.efficiency_test(x0)
                if eff is None:
                    break
                if eff:
                    psi_star, x_star = psi0, x0
                    break
                xs, ps = self.find_best(xp)
                if self.truncated:
                    break
                if ps > psi_star:
                    psi_star, x_star = ps, xs
                    if bound is not None:
                        self.mR.remove(bound)
                    bound = self.mR.addConstr(
                        gp.quicksum((float(p[j]) - psi_star * float(q[j]))
                                    * self.xR[j] for j in range(self.n))
                        >= psi_star * be - al)
                self.add_cut(xp)
            else:
                self.rounds_exhausted = True

        return dict(psi=psi_star, x=x_star, cuts=self.cuts, milps=self.milps,
                    t_milp=self.t_milp, t_wall=time.perf_counter() - t_wall,
                    truncated=self.truncated, rounds_exhausted=self.rounds_exhausted,
                    loose_bounds=self.loose_bounds, rounds=rounds,
                    seed_milps=self.seed_milps)


def _run_cfg(inst, name, seeds, time_limit=60, wall_budget=120):
    if name == "base":
        s = Method(inst, time_limit=time_limit, wall_budget=wall_budget)
    else:
        s = SeededMethod(inst, seeds=seeds, cut_seeds=(name == "seedcut"),
                         time_limit=time_limit, wall_budget=wall_budget)
    try:
        res = s.solve()
    finally:
        s.close()
    res.setdefault("rounds", res["cuts"])
    res.setdefault("seed_milps", 0)
    return res


CFGS = ("base", "seed", "seedcut")


# ------------------------------------------------------------------ validate
def validate(seeds=8, reps=30):
    print("VALIDATE -- seeded variants against exhaustive enumeration")
    rng = np.random.default_rng(RNG_SEED)
    ok = tot = 0
    for _ in range(reps):
        inst = generate_instance(rng, n=6, m=2, r=3, ub=3)
        truth = brute_force(inst)
        if truth is None:
            continue
        tot += 1
        good = True
        for name in CFGS:
            res = _run_cfg(inst, name, seeds)
            if res["truncated"] or res["rounds_exhausted"]:
                print(f"  TRUNCATED cfg={name} -- proves nothing")
                good = False
                break
            if not np.isfinite(res["psi"]) or abs(res["psi"] - truth) > 1e-6:
                print(f"  MISMATCH cfg={name} got={res['psi']} expected={truth}")
                good = False
                break
        ok += good
    print(f"  {ok}/{tot} instances optimal under all three configurations")
    print("VALIDATION PASSED" if ok == tot and tot > 0 else "VALIDATION FAILED")


# ------------------------------------------------------------------- compare
def compare(big=False, rho=None, reps=8, seeds=8):
    cfg, rho = (BIG if big else SMALL), (RHO[big] if rho is None else rho)
    print(f"COMPARE -- n={cfg['n']} m={cfg['m']} r={cfg['r']} rho={rho} "
          f"seeds={seeds}\n")
    rng = np.random.default_rng(RNG_SEED)
    rows = []
    for rep in range(reps):
        inst = generate_instance(rng, ub=10, rho=rho, **cfg)
        rec = dict(rep=rep)
        ref = None
        for name in CFGS:
            res = _run_cfg(inst, name, seeds)
            for key in ("t_milp", "milps", "cuts", "rounds", "psi", "seed_milps"):
                rec[f"{name}_{key}"] = res[key]
            rec[f"{name}_trunc"] = bool(res["truncated"] or res["rounds_exhausted"])
            if ref is None:
                ref = res["psi"]
            rec[f"{name}_agree"] = bool(np.isfinite(res["psi"])
                                        and np.isfinite(ref)
                                        and abs(res["psi"] - ref) < 1e-6)
        rows.append(rec)
        print("  rep %d: " % rep + " | ".join(
            f"{c} {rec[c+'_t_milp']:6.2f}s r={rec[c+'_rounds']:2d} "
            f"cuts={rec[c+'_cuts']:2d} milp={rec[c+'_milps']:3d}" for c in CFGS)
            + ("  <-- TRUNCATED" if any(rec[c + "_trunc"] for c in CFGS) else ""),
            flush=True)

    df = pd.DataFrame(rows)
    df.to_csv("rounds_raw.csv", index=False)
    clean = df[~df[[c + "_trunc" for c in CFGS]].any(axis=1)]
    print("\n" + "=" * 78)
    for c in CFGS[1:]:
        print(f"  {c:<8} agrees with base in {int(df[c+'_agree'].sum())}/{len(df)}")
    print(f"  runs where nothing truncated: {len(clean)}/{len(df)}")
    if not len(clean):
        print("  nothing usable; raise the wall budget or lower rho")
        return

    print("\n" + "=" * 78)
    print(f"{'cfg':<9}{'time (s)':>10}{'rounds':>9}{'cuts':>7}{'#MILP':>8}"
          f"{'of which seed':>15}{'ms/MILP':>10}{'vs base':>10}")
    b = clean["base_t_milp"].median()
    for c in CFGS:
        t, k = clean[c + "_t_milp"], clean[c + "_milps"]
        print(f"{c:<9}{t.median():>10.2f}{clean[c+'_rounds'].median():>9.0f}"
              f"{clean[c+'_cuts'].median():>7.0f}{k.median():>8.0f}"
              f"{clean[c+'_seed_milps'].median():>15.0f}"
              f"{(1000*t/k).median():>10.1f}"
              f"{100*(t.median()-b)/max(b,1e-9):>9.1f}%")

    try:
        from scipy.stats import wilcoxon
    except ImportError:
        wilcoxon = None
    print("\nPAIRED TESTS on time inside the solver")
    for c in CFGS[1:]:
        a, z = clean["base_t_milp"], clean[c + "_t_milp"]
        w = wilcoxon(a, z) if (wilcoxon is not None and (a != z).any()) else None
        print(f"  base vs {c:<8} median change "
              f"{100*(z-a).median()/max(a.median(),1e-9):+7.1f}%  "
              f"p={'n/a' if w is None else f'{w.pvalue:.3g}'}  "
              f"better in {int((z<a).sum())}/{len(clean)}")
    print("\nwritten: rounds_raw.csv")


