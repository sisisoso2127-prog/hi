"""Attack the number of rounds, the factor the original decomposition retired.

WHY THIS IS BACK ON THE TABLE

The decomposition that directed all earlier work said the subproblem count grows
x1.23 and so is not worth attacking. That figure was measured across n on the
original grid -- where sum_j x_j sits at about 3.5 whatever n is, so raising n
raised nothing. Re-measured on the fixed grid, across the tightness axis that
does make these instances hard, the subproblem count grows x3.4 and the cut
count x3.2 alongside it. The two move together because every round emits exactly
one cut and one batch of subproblems, so the round count drives both factors at
once. And hull_experiment.py established that what makes a residual-region solve
expensive is model size, which is the cut count. Rounds are therefore the one
quantity that sits on both halves of the decomposition.

THE LEVER

The algorithm's own bound (Remark 3.4) restricts the residual region to
psi(x) >= psi*, but psi* starts at -infinity, so the first rounds search the
whole region and psi* only creeps up as slices are evaluated. Every efficient
point found anywhere is a valid psi*, and a weighted-sum scalarisation
max sum_i lam_i c^i x with lam > 0 returns an efficient point for a few
milliseconds on a model that carries no cuts at all.

  SEED     -- before the main loop, take S such points, run Find-Best on each to
              get the best psi on its criterion slice, and enter the loop with
              psi* already high. Costs S*(1 + Find-Best) subproblems on the
              CHEAP uncut model and adds ONE linear constraint. The model never
              grows: this is the only lever tried so far that cannot make a
              residual solve more expensive.

  SEEDCUT  -- the same, and additionally cut each seeded point. Strictly more
              pruning per round, but it does grow the model, which is the thing
              that was just shown to dominate. Included to separate the two
              effects rather than assume which one carries.

Exactness is untouched. A weighted-sum optimum with strictly positive weights is
efficient, so psi* seeded from one is attained at an efficient point and the
answer is at least psi*; restricting to psi >= psi* discards nothing. Cutting a
seeded point is valid on the same argument the main loop uses -- Find-Best has
already maximised psi over that point's whole criterion slice before the slice
is removed. Both are checked against exhaustive enumeration by 'validate',
which is the first thing to run.

    python3 rounds_experiment.py validate        # correctness first
    python3 rounds_experiment.py compare         # the measurement
    python3 rounds_experiment.py compare --seeds 4    # sweep the seed count

WHAT THIS FOUND, AND WHY THE LEVER CANNOT WORK

SEED does not reduce the round count at all. Four instances, rounds base -> seed:
24 -> 25, 55 -> 55, 37 -> 38, 60 -> 60. Time moved -4.7% on two clean runs, p=1.
Not a weak effect; no effect.

The reason is structural and kills every variant of the idea. The bound keeps
only psi(x) >= psi*, but the rounds are generated by NON-EFFICIENT points that
top the psi ranking, and those sit ABOVE the efficient optimum, not below it.
Measured on six instances: the psi maximum over the whole region is a median
3.74x the psi of the efficient optimum, and on one instance 3.34 against 0.174,
a factor of 19. The entire band between the two is non-efficient and scores
above psi*, so raising psi* -- by seeding, by a better primal heuristic, by any
means whatever -- cannot exclude one point of it. That retires incumbent quality
as a lever the same way the frozen root bound retired the big-M constant.

SEEDCUT does cut rounds sometimes (55 -> 49, 37 -> 29) because extra cuts remove
extra boxes, and it pays for them in model size: 45.97s -> 46.09s on the instance
where it saved 18% of the subproblems. Which closes the loop on every result in
this repository. The round count is set by how many dominated boxes lie in that
non-efficient band, an instance property; reducing it means cutting more per
round; more cuts is a bigger model; and model size is what hull_experiment.py
showed dominates the cost. There is no way to spend less here without spending
more somewhere that costs more.

Run 'compare' if you want the full sweep, but the mechanism is already settled
by the round counts, which are unambiguous and do not depend on timing noise.
"""

